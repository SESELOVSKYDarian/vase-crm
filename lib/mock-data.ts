// -------- Helpers de lookup, usados por las pantallas --------
export function getClient(id: string) {
  return clients.find((c) => c.id === id);
}
export function getQuote(id: string) {
  return quotes.find((q) => q.id === id);
}
export function getWorkOrder(id: string) {
  return workOrders.find((o) => o.id === id);
}
export function workOrdersForClient(clienteId: string) {
  return workOrders.filter((o) => o.clienteId === clienteId);
}
export function quotesForClient(clienteId: string) {
  return quotes.filter((q) => q.clienteId === clienteId);
}
export function invoicesForClient(clienteId: string) {
  return invoices.filter((i) => i.clienteId === clienteId);
}
export function paymentsForClient(clienteId: string) {
  return payments.filter((p) => p.clienteId === clienteId);
}
export function accountMovementsForClient(clienteId: string) {
  return accountMovements.filter((m) => m.clienteId === clienteId);
}
export function balanceForClient(clienteId: string) {
  const movs = accountMovementsForClient(clienteId);
  return movs.length ? movs[movs.length - 1].saldo : 0;
}
